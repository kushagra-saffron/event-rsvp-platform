/** Local-time strings HH:mm on 15-minute steps (96 options per day). */
export const QUARTER_HOUR_TIMES = ((): string[] => {
  const out: string[] = [];
  for (let h = 0; h < 24; h++) {
    for (const m of [0, 15, 30, 45]) {
      out.push(`${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}`);
    }
  }
  return out;
})();
